import { describe, expect, test } from 'bun:test'
import { toEventSelector, zeroAddress } from '@zoltar/core-shared/evm/ethereum'
import { createWriteClient, writeContractAndWait } from '../../testSupport/simulator/utils/clients'
import { getForkActivationTime } from '../../testSupport/simulator/utils/contracts/securityPoolForker'
import { getSecurityVault } from '../../testSupport/simulator/utils/contracts/securityPool'
import { combineUint256FromTwoWithInvalid } from '../../testSupport/simulator/utils/contracts/zoltarQuestionData'
import { requireArray } from '../../testSupport/simulator/utils/utilities'
import { statoblast_SecurityPoolPortfolioRecovery_SecurityPoolPortfolioRecovery as recoveryArtifact, statoblast_SecurityPoolForker_SecurityPoolForker as forkerArtifact, statoblast_SecurityPool_SecurityPool as poolArtifact } from '../../types/contractArtifact'
import { aggregatePortfolioAbi } from './securityPoolPortfolioAggregateFixture'
import { unit } from './securityPoolPortfolioFixture'
import { nativeMigrationDuration, sharedChoiceDuration, sharedForkControllerAbi, useSharedPortfolioForkFixture } from './securityPoolPortfolioSharedForkFixture'

describe('Statoblast: shared portfolio fork migration', () => {
	const { fixture, allocate, fork, prepareChild, controller, choose, process, childContext, branchWeight, forkPosition, revoke, window, claim, custody, ownerPositionShares, deposit, mint, assets } = useSharedPortfolioForkFixture()
	const choice = async (owner = fixture.owner(), contextId = 0n, intervalId = 0n) => requireArray(await fixture.owner().readContract({ abi: sharedForkControllerAbi, address: await controller(), functionName: 'choices', args: [contextId, owner.account.address, intervalId] }), 'Shared choice')
	const individualMigrate = (owner = fixture.other(), outcome = 2n, positionId = 1n, intervalId = 0n) => writeContractAndWait(owner, () => owner.writeContract({ abi: aggregatePortfolioAbi, address: fixture.portfolio, functionName: 'claimPositionAndMigrate', args: [positionId, intervalId, outcome] }))

	test('three owners choose once and each funded question migrates once for their common branch', async () => {
		const owners = await allocate(3)
		const sourceFork = await fork()
		expect(await controller()).not.toBe(zeroAddress)
		for (const owner of owners) await choose(1n, owner)
		for (const positionId of [1n, 2n]) expect(await branchWeight(positionId)).toBe(15_000n * unit)
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		const context = await childContext()
		expect(context).toBeGreaterThan(0n)
		for (const positionId of [1n, 2n]) {
			const questionId = positionId === 1n ? fixture.base.questionId : fixture.secondQuestionId
			const parent = fixture.poolFor(questionId).securityPool
			const child = await prepareChild(parent, 1n, questionId)
			const migrationEvent = forkerArtifact.abi.find(item => item.type === 'event' && item.name === 'VaultMigrationCheckpoint')
			if (migrationEvent === undefined) throw new Error('Missing native migration checkpoint ABI')
			const hash = await process(positionId)
			const receipt = await fixture.other().waitForTransactionReceipt({ hash })
			expect(receipt.logs.filter(log => log.topics[0] === toEventSelector(migrationEvent))).toHaveLength(1)
			expect(receipt.gasUsed).toBeLessThan(16_777_216n)
			const migrated = await forkPosition(context, positionId)
			expect(migrated[0]).not.toBe(zeroAddress)
			expect(migrated[1]).toBe(15_000n * unit)
			expect((await getSecurityVault(fixture.owner(), child, migrated[0])).repBackingUnits).toBeGreaterThan(0n)
			expect((await forkPosition(0n, positionId))[2]).toBe(0n)
			const duplicate = await fixture.other().waitForTransactionReceipt({ hash: await process(positionId) })
			expect(duplicate.logs.filter(log => log.topics[0] === toEventSelector(migrationEvent))).toHaveLength(0)
			expect(await forkPosition(context, positionId)).toEqual(migrated)
		}
	})

	test('allocation snapshots retain their different owner weights across one common branch choice', async () => {
		await deposit()
		await fixture.refreshPrice(fixture.base.questionId)
		await mint(20n * unit)
		await deposit(await assets(), fixture.other())
		await mint(20n * unit, fixture.secondQuestionId)
		await fork()
		await choose()
		await choose(1n, fixture.other())
		expect(await branchWeight(1n)).toBe(5_000n * unit)
		expect(await branchWeight(2n)).toBe(10_000n * unit)
		const ledger = await fixture.owner().readContract({ abi: aggregatePortfolioAbi, address: fixture.portfolio, functionName: 'recoveryLedger' })
		expect(await fixture.owner().readContract({ abi: recoveryArtifact.abi, address: ledger, functionName: 'getOwnerIntervalCount', args: [fixture.owner().account.address] })).toBe(1n)
	})

	test('a pre-fork individual exit stays excluded from later shared enrollment', async () => {
		await allocate()
		await claim()
		await fork()
		await expect(choose()).rejects.toThrow()
		await choose(1n, fixture.owner(), 0n, [1n])
		await choose(1n, fixture.other())
		expect(await branchWeight(1n)).toBe(5_000n * unit)
		expect(await branchWeight(2n)).toBe(10_000n * unit)
		expect(await ownerPositionShares()).toBe(0n)
	})

	test('a small branch migrates its existing share without meeting a new-vault deposit minimum', async () => {
		await deposit()
		await deposit(1_000_000_000n, fixture.other())
		await fixture.refreshPrice(fixture.base.questionId)
		await mint(20n * unit)
		const sourceFork = await fork()
		await choose(1n, fixture.other())
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		const parent = fixture.base.securityPoolAddresses.securityPool
		const child = await prepareChild(parent, 1n)
		await process()
		const migrated = await forkPosition(await childContext())
		// Native migration initializes child units in attoREP; the full pool-held REP split remains lazy.
		const backing = (await getSecurityVault(fixture.owner(), child, migrated[0])).repBackingUnits
		const minimum = await fixture.owner().readContract({ abi: poolArtifact.abi, address: child, functionName: 'minimumVaultRepDepositAttoRep' })
		expect(backing).toBeGreaterThan(0n)
		expect(backing).toBeLessThan(minimum)
		expect(migrated[1]).toBe(1_000_000_000n)
	})

	test('choice changes update both question weights and never choose for another owner', async () => {
		await allocate()
		await expect(choose()).rejects.toThrow()
		await fork()
		await choose(0n)
		expect((await choice())[0]).toBe(true)
		expect((await choice())[1]).toBe(0n)
		for (const positionId of [1n, 2n]) expect(await branchWeight(positionId, 0n)).toBe(5_000n * unit)
		await expect(claim()).rejects.toThrow()
		await choose(2n)
		for (const positionId of [1n, 2n]) {
			expect(await branchWeight(positionId, 0n)).toBe(0n)
			expect(await branchWeight(positionId, 2n)).toBe(5_000n * unit)
		}
		expect((await choice(fixture.other()))[0]).toBe(false)
		await expect(choose(1n, fixture.owner(), 0n, [0n, 0n])).rejects.toThrow()
		await expect(choose(1n, fixture.other(), 0n, [1n])).rejects.toThrow()
		await revoke()
		expect((await choice())[0]).toBe(false)
		expect(await branchWeight(1n, 2n)).toBe(0n)
		await claim()
		expect(await ownerPositionShares()).toBe(0n)
	})

	test('the shared cutoff is anchored to the universe fork and remains separate from native activation', async () => {
		await allocate()
		const sourceFork = await fork({ activatePools: false })
		const [opensAt, closesAt] = await window()
		expect(opensAt).toBe(sourceFork.forkTime)
		expect(closesAt).toBe(sourceFork.forkTime + sharedChoiceDuration)
		await choose()
		await expect(process()).rejects.toThrow()
		await fixture.base.mockWindow.setTime(closesAt)
		const address = await controller()
		await fixture.other().readContract({ abi: sharedForkControllerAbi, address, functionName: 'chooseSharedFork', args: [0n, [0n], 1n], account: fixture.other().account.address })
		await expect(fixture.other().readContract({ abi: sharedForkControllerAbi, address, functionName: 'processForkPosition', args: [0n, 1n, 1n], account: fixture.other().account.address })).rejects.toThrow()
		await fixture.base.mockWindow.advanceTime(1n)
		await expect(choose(2n)).rejects.toThrow()
		await expect(revoke()).rejects.toThrow()
		await expect(choose(1n, fixture.other())).rejects.toThrow()
		expect(await window()).toEqual([opensAt, closesAt])
	})

	test('different scalar and invalid branches process independently with no three-outcome assumption', async () => {
		await allocate()
		const sourceFork = await fork({ scalar: true })
		const scalar = combineUint256FromTwoWithInvalid(false, 37n, 63n)
		expect(scalar).toBeGreaterThan(2n ** 255n)
		await choose(scalar)
		await choose(0n, fixture.other())
		await expect(choose(3n)).rejects.toThrow()
		expect(await branchWeight(1n, scalar)).toBe(5_000n * unit)
		expect(await branchWeight(1n, 0n)).toBe(5_000n * unit)
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		const parent = fixture.base.securityPoolAddresses.securityPool
		const scalarChild = await prepareChild(parent, scalar)
		await process(1n, scalar)
		const scalarPosition = await forkPosition(await childContext(scalar))
		expect((await getSecurityVault(fixture.owner(), scalarChild, scalarPosition[0])).repBackingUnits).toBeGreaterThan(0n)
		expect((await forkPosition(await childContext(0n)))[0]).toBe(zeroAddress)
		expect((await forkPosition(0n))[2]).toBe(5_000n * unit)
		const invalidChild = await prepareChild(parent, 0n)
		await process(1n, 0n)
		const invalidPosition = await forkPosition(await childContext(0n))
		expect((await getSecurityVault(fixture.owner(), invalidChild, invalidPosition[0])).repBackingUnits).toBeGreaterThan(0n)
		expect((await forkPosition(0n))[2]).toBe(0n)
		expect((await forkPosition(0n, 2n))[2]).toBe(10_000n * unit)
	})

	test('missing child preparation cannot consume shared weights or native backing', async () => {
		await allocate()
		const sourceFork = await fork()
		await choose()
		await choose(1n, fixture.other())
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		const source = await custody()
		const before = await getSecurityVault(fixture.owner(), fixture.base.securityPoolAddresses.securityPool, source)
		const beforePosition = await forkPosition(0n)
		await expect(process()).rejects.toThrow()
		expect(await forkPosition(0n)).toEqual(beforePosition)
		expect(await branchWeight()).toBe(10_000n * unit)
		expect((await forkPosition(await childContext()))[0]).toBe(zeroAddress)
		expect(await getSecurityVault(fixture.owner(), fixture.base.securityPoolAddresses.securityPool, source)).toEqual(before)
		await prepareChild(fixture.base.securityPoolAddresses.securityPool, 1n)
		await process()
		expect((await forkPosition(0n))[2]).toBe(0n)
	})

	for (const sharedFirst of [true, false])
		test(`shared and individual migrations conserve backing when ${sharedFirst ? 'shared' : 'individual'} goes first`, async () => {
			await allocate()
			const parent = fixture.base.securityPoolAddresses.securityPool
			const source = await custody()
			const before = await getSecurityVault(fixture.owner(), parent, source)
			const beforeBacking = await fixture.repClaim(parent, source)
			const badDebt = 7n * unit + 3n
			const forker = await fixture.owner().readContract({ abi: poolArtifact.abi, address: parent, functionName: 'securityPoolForker' })
			await fixture.base.mockWindow.impersonateAccount(forker)
			await fixture.base.mockWindow.setBalance(forker, unit)
			const forkerClient = createWriteClient(fixture.base.mockWindow, BigInt(forker))
			// Isolate migration debt arithmetic through the native forker's existing fixture setter.
			await writeContractAndWait(forkerClient, () => forkerClient.writeContract({ abi: poolArtifact.abi, address: parent, functionName: 'configureVault', args: [source, before.repBackingUnits, before.underwritingLimitAttoEth, before.feeIndex, badDebt, badDebt] }))
			const sourceFork = await fork()
			const otherVault = await fixture.createVault(fixture.other())
			await choose()
			await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
			const sharedChild = await prepareChild(parent, 1n)
			const individualChild = await prepareChild(parent, 2n)
			if (sharedFirst) await process()
			await individualMigrate()
			if (!sharedFirst) await process()
			const sharedVault = (await forkPosition(await childContext()))[0]
			const grouped = await getSecurityVault(fixture.owner(), sharedChild, sharedVault)
			const individual = await getSecurityVault(fixture.owner(), individualChild, otherVault)
			expect(grouped.repBackingUnits + individual.repBackingUnits).toBe(beforeBacking)
			expect(grouped.underwritingLimitAttoEth + individual.underwritingLimitAttoEth).toBe(before.underwritingLimitAttoEth)
			const sharedDebt = await fixture.owner().readContract({ abi: poolArtifact.abi, address: sharedChild, functionName: 'vaultBadDebtAttoEth', args: [sharedVault] })
			const individualDebt = await fixture.owner().readContract({ abi: poolArtifact.abi, address: individualChild, functionName: 'vaultBadDebtAttoEth', args: [otherVault] })
			expect(sharedDebt + individualDebt).toBe(badDebt)
			expect(await fixture.owner().readContract({ abi: poolArtifact.abi, address: parent, functionName: 'vaultBadDebtAttoEth', args: [source] })).toBe(0n)
			expect((await getSecurityVault(fixture.owner(), parent, await custody())).repBackingUnits).toBe(0n)
			const remaining = await forkPosition(0n)
			expect(remaining[1]).toBe(5_000n * unit)
			expect(remaining[2]).toBe(0n)
			expect(remaining[3]).toBe(true)
			expect(await fixture.owner().readContract({ abi: aggregatePortfolioAbi, address: fixture.portfolio, functionName: 'processingRewards', args: [fixture.other().account.address] })).toBe(250_000_000_000_000n)
			expect(await ownerPositionShares(1n, fixture.other().account.address)).toBe(0n)
			expect(await ownerPositionShares()).toBe(5_000n * unit)
		})

	test('an owner missing the shared cutoff retains the full inclusive native migration deadline', async () => {
		await allocate()
		const sourceFork = await fork()
		await choose()
		const parent = fixture.base.securityPoolAddresses.securityPool
		const deadline = (await getForkActivationTime(fixture.owner(), parent)) + nativeMigrationDuration
		await prepareChild(parent, 1n)
		const individualChild = await prepareChild(parent, 2n)
		const otherVault = await fixture.createVault(fixture.other())
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		await process()
		await fixture.base.mockWindow.setTime(deadline - 1n)
		await individualMigrate()
		expect(await fixture.base.mockWindow.getTime()).toBe(deadline)
		expect((await getSecurityVault(fixture.owner(), individualChild, otherVault)).repBackingUnits).toBeGreaterThan(0n)
	})

	test('an expired shared migration leaves the source ownership and weights intact', async () => {
		await allocate()
		await fork()
		await choose()
		const parent = fixture.base.securityPoolAddresses.securityPool
		await prepareChild(parent, 1n)
		await fixture.base.mockWindow.setTime((await getForkActivationTime(fixture.owner(), parent)) + nativeMigrationDuration + 1n)
		const before = await forkPosition(0n)
		await expect(process()).rejects.toThrow('Migration window closed')
		expect(await forkPosition(0n)).toEqual(before)
		expect(await branchWeight()).toBe(5_000n * unit)
		await expect(individualMigrate()).rejects.toThrow('Migration window closed')
		expect(await ownerPositionShares(1n, fixture.other().account.address)).toBe(5_000n * unit)
	})

	test('pre-fork liquid REP and fees remain common historical proceeds after a shared branch migrates', async () => {
		await allocate()
		const source = await custody()
		await fixture.transferRep(source, 8n * unit)
		await writeContractAndWait(fixture.owner(), () => fixture.owner().sendTransaction({ to: source, value: 3n * unit }))
		const sourceFork = await fork()
		await choose()
		await choose(2n, fixture.other())
		await fixture.base.mockWindow.setTime(sourceFork.forkTime + sharedChoiceDuration + 1n)
		await prepareChild(fixture.base.securityPoolAddresses.securityPool, 1n)
		await process()
		const ledger = await fixture.owner().readContract({ abi: aggregatePortfolioAbi, address: fixture.portfolio, functionName: 'recoveryLedger' })
		const preview = (owner = fixture.owner()) => owner.readContract({ abi: recoveryArtifact.abi, address: ledger, functionName: 'previewClaim', args: [owner.account.address, [0n]] })
		const first = await preview()
		expect(first[0]).toBe(4n * unit)
		expect(first[1]).toBeGreaterThanOrEqual((3n * unit) / 2n)
		expect(await preview(fixture.other())).toEqual(first)
		await prepareChild(fixture.base.securityPoolAddresses.securityPool, 2n)
		await process(1n, 2n)
		expect(await preview()).toEqual(first)
		expect(await preview(fixture.other())).toEqual(first)
	})
})
